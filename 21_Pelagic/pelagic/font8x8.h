static inline const uint8_t *font8x8_glyph(char c)
{
    if (c == ' ') return font8x8_data[0];
    if (c >= 'A' && c <= 'Z') return font8x8_data[1 + (c - 'A')];
    if (c >= 'a' && c <= 'z') return font8x8_data[1 + (c - 'a')];
    if (c >= '0' && c <= '9') return font8x8_data[27 + (c - '0')];
    if (c == '-') return font8x8_data[37];
    if (c == '.') return font8x8_data[38];
    if (c == '!') return font8x8_data[39];
    if (c == ':') return font8x8_data[40];
    return font8x8_data[0];
}

