static inline const uint8_t *font8x12_glyph(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z') return font8x12_data[1 + (c - 'A')];
    if (c >= '0' && c <= '9') return font8x12_data[27 + (c - '0')];
    if (c == ':') return font8x12_data[37];
    if (c == '.') return font8x12_data[38];
    if (c == '-') return font8x12_data[39];
    return font8x12_data[0];
}
